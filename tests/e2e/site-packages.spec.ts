import { expect, test } from "@playwright/test";
import { TENANT_BASE } from "./helpers";

test.use({ viewport: { width: 1440, height: 900 } });

test("every event's packages show without JavaScript", async ({ browser }) => {
  const context = await browser.newContext({ javaScriptEnabled: false, viewport: { width: 375, height: 800 } });
  const page = await context.newPage();
  await page.goto(TENANT_BASE);
  const packages = page.locator("#packages");
  await expect(packages.getByRole("tablist")).toBeHidden();
  await expect(packages.getByRole("heading", { name: "Mehndi", exact: true })).toBeVisible();
  await expect(packages.getByText("Rs 2,600").first()).toBeVisible();
  await context.close();
});

test("package tabs follow the WAI-ARIA keyboard pattern", async ({ page }) => {
  await page.goto(TENANT_BASE);
  const tablist = page.locator("#packages").getByRole("tablist");
  const tab = (name: string) => tablist.getByRole("tab", { name, exact: true });
  const selected = tablist.locator('[role=tab][aria-selected="true"]');
  await expect(selected).toHaveText("Barat");
  await expect(selected).toHaveAttribute("tabindex", "0");

  // Retried: a key pressed before hydration on a cold dev server does nothing.
  await expect(async () => {
    await tab("Barat").focus();
    await page.keyboard.press("ArrowRight");
    await expect(tab("Valima")).toHaveAttribute("aria-selected", "true", { timeout: 1000 });
  }).toPass({ timeout: 30_000 });
  await expect(tab("Valima")).toBeFocused();
  await expect(tab("Barat")).toHaveAttribute("tabindex", "-1");
  await expect(page.locator("#packages").getByRole("tabpanel")).toHaveAccessibleName("Valima");

  await page.keyboard.press("Home");
  await expect(tab("Mehndi")).toBeFocused();
  await page.keyboard.press("Alt+ArrowRight");
  await expect(tab("Mehndi")).toBeFocused();
  await expect(tab("Mehndi")).toHaveAttribute("aria-selected", "true");
  await page.keyboard.press("ArrowLeft");
  await expect(tab("Corporate")).toHaveAttribute("aria-selected", "true");
  await expect(tab("Corporate")).toBeFocused();
  await page.keyboard.press("Home");
  await expect(tab("Mehndi")).toBeFocused();
  await page.keyboard.press("End");
  await expect(tab("Corporate")).toBeFocused();
});

test("choosing a package fills the enquiry until the event changes", async ({ page }) => {
  const preview = page.locator("#contact [aria-live=polite]");
  const guests = page.locator("#contact").getByLabel("Number of guests");
  // Retried: a click before hydration on a cold dev server only follows the link.
  await expect(async () => {
    await page.goto(TENANT_BASE);
    await page.locator("#packages").getByRole("link", { name: "Choose Gold" }).click();
    await expect(preview).toContainText("Package: Gold (Rs 4,200 per guest)", { timeout: 1000 });
  }).toPass({ timeout: 30_000 });
  await expect(page).toHaveURL(/#contact$/);
  // The form showed 400, above Gold's minimum of 300, so it stays.
  await expect(guests).toHaveValue("400");
  await guests.fill("200");
  await page.locator("#packages").getByRole("link", { name: "Choose Gold" }).click();
  await expect(guests).toHaveValue("300");
  await expect(preview).toContainText("Guests: about 300");
  await page.locator("#contact").getByText("Valima", { exact: true }).click();
  await expect(preview).not.toContainText("Package:");
});
