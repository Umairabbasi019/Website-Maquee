import { existsSync, readFileSync } from "node:fs";
import { join } from "node:path";
import type { SupabaseClient } from "@supabase/supabase-js";
import { demoMedia, LICENCE, manorMedia, type SeedMedia } from "./seed-data/media-manifest";

const BUCKET = "venue-media";
const DEMO_DIR = join(import.meta.dirname, "seed-data", "demo-media");
const DEFAULT_MANOR_DIR = ".superpowers/brainstorm/1089-1792319084/content";

type Size = "s" | "m" | "l";
type Asset = Omit<SeedMedia, "source"> & { source: string | null; files: Partial<Record<Size, string>> };

function failIf(error: { message: string } | null, what: string) {
  if (error) throw new Error(`${what}: ${error.message}`);
}

function manorAssets(): Asset[] {
  return manorMedia.map((m) =>
    m.ext === "png"
      ? { ...m, files: { m: `${m.key}.png` } }
      : { ...m, files: { s: `e-${m.key}-s.jpg`, m: `e-${m.key}.jpg`, l: `e-${m.key}-l.jpg` } },
  );
}

// Demo images are generated by tools/make_demo_images.py: s and m only, so the fallback to the nearest size gets exercised.
function demoAssets(): Asset[] {
  return demoMedia.map((m) => ({ ...m, source: "generated placeholder (tools/make_demo_images.py)", files: { s: `${m.key}-s.jpg`, m: `${m.key}-m.jpg` } }));
}

async function seedTenantMedia(admin: SupabaseClient, slug: string, dir: string, assets: Asset[]) {
  const { data, error } = await admin.from("tenants").select("id").eq("slug", slug).single();
  failIf(error, `tenant ${slug}`);
  const tenantId: string = data!.id;
  const rows = [];
  for (const a of assets) {
    const present = Object.entries(a.files).filter(([, name]) => existsSync(join(dir, name)));
    if (!present.length) throw new Error(`${slug}/${a.key}: no image file found in ${dir}`);
    const ext = a.ext ?? "jpg";
    for (const [size, name] of present) {
      const { error: upError } = await admin.storage
        .from(BUCKET)
        .upload(`${tenantId}/${a.key}/${size}.${ext}`, readFileSync(join(dir, name)), {
          upsert: true,
          contentType: ext === "png" ? "image/png" : "image/jpeg",
          cacheControl: "31536000",
        });
      failIf(upError, `upload ${slug}/${a.key}/${size}`);
    }
    rows.push({
      tenant_id: tenantId,
      key: a.key,
      alt: a.alt,
      category: a.category,
      source: a.source,
      licence: LICENCE,
      sizes: present.map(([size]) => size),
      ext,
    });
  }
  failIf((await admin.from("media_assets").upsert(rows, { onConflict: "tenant_id,key" })).error, `media_assets ${slug}`);
}

export async function seedMedia(admin: SupabaseClient) {
  await seedTenantMedia(admin, "demo-hall", DEMO_DIR, demoAssets());
  if (process.env.SKIP_MANOR_MEDIA === "1") return;
  const manorDir = process.env.MANOR_MEDIA_DIR || DEFAULT_MANOR_DIR;
  if (!existsSync(manorDir)) {
    throw new Error(`Manor media folder not found: ${manorDir}. Set MANOR_MEDIA_DIR, or SKIP_MANOR_MEDIA=1 to seed without Manor photos.`);
  }
  await seedTenantMedia(admin, "manor", manorDir, manorAssets());
}
